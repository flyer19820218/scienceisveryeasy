import streamlit as st

def render_reading_and_quiz():
    st.markdown("### 📜 黎明韓流 S02E01 機密任務：碳基生命的審判")
    st.info("💡 **總製作人黎明**：『在娛樂圈，不是有包裝的都是真偶像；在化學界，也不是所有含碳的都是有機物。看清本質，才是生存的唯一法則。』")
    
    # 📖 素養閱讀區
    st.markdown("#### 📖 賽前機密檔案：有機物的血統證明")
    st.write("在十八世紀以前，化學界流傳著一個神話：**「只有具備生命力的動植物，才能製造出有機化合物。」** 當時的人們認為，礦物或石頭這類死物，只能產出無機物。")
    st.write("直到 1828 年，德國化學家 **烏拉 (Wöhler)** 意外在實驗室裡，用無機物加熱合成出尿液中的成分——「尿素」。這個巴掌重重打醒了科學界，徹底打破了生命力的迷思！")
    
    st.markdown("##### ⚠️ 現代鐵律與「四大叛徒」")
    st.write("現在，科學界重新定義了有機物：**只要成分中「含有碳元素（C）」，就是有機化合物！**")
    st.error("但是！有四個傢伙雖然身上流著碳的血，但化學行為卻跟無機物一模一樣，被我們稱為有機物宇宙的 **『四大叛徒』**（屬於無機化合物）：\n"
             "1. **一氧化碳 (CO)**\n"
             "2. **二氧化碳 (CO₂)**\n"
             "3. **碳酸鹽類** (例如大理石的主要成分：碳酸鈣 CaCO₃)\n"
             "4. **氰化物** (例如劇毒的 KCN)")

    st.write("---")
    
    # 🔍 素養情境題
    st.markdown("#### 🔍 舞台突發狀況 (情境考核)")
    st.write("在「無人島求生」關卡中，四號練習生興奮地舉起一塊白色的**大理石（主要成分為碳酸鈣 CaCO₃）**，對著鏡頭大喊：「我找到了含有碳元素的物質！這絕對是有機化合物，可以用來當作我們的生火燃料！」")
    
    q1 = st.radio(
        "身為總製作人，請你按下麥克風，給這位練習生最無情的評判：",
        [
            "A. 「沒錯！只要有碳元素就是有機物，拿去燒吧！」",
            "B. 「愚蠢。碳酸鈣屬於『碳酸鹽類』，是有機物定義中的四大叛徒，它是無機物！」",
            "C. 「答對一半。它是無機物，但大理石是烏拉在實驗室合成出來的。」",
            "D. 「淘汰。有機化合物裡面絕對不能含有『鈣』這種金屬元素。」"
        ],
        index=None
    )
    
    if st.button("🛡️ 提交評判", use_container_width=True):
        if q1 is None:
            st.warning("請先選擇一個選項再送出！")
        elif q1.startswith("B"):
            st.success("✅ 評判精準！你成功點出了『四大叛徒』的陷阱，大理石是無機物且無法燃燒。審判通過，準備進入正式挑戰！")
            return True
        else:
            st.error("❌ 評判失誤！請重新閱讀上方關於『現代鐵律與四大叛徒』的機密檔案，想一想大理石（碳酸鈣）到底屬於哪一類？")
            
    return False
